import { copyFile, mkdir, readdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const frontend = resolve(here, "..");
const repo = resolve(frontend, "..");
const data = join(frontend, "src", "data");
const evidence = join(data, "evidence");

await mkdir(evidence, { recursive: true });

const sources = [
  [join(repo, "contracts", "deployments.json"), join(data, "deployments.json"), "deployments"],
  [join(repo, "contracts", "seed.json"), join(data, "seed.json"), "seed"],
];

const evidenceFiles = (await readdir(join(repo, "evidence"))).filter((name) => name.endsWith(".json")).sort();
for (const name of evidenceFiles) {
  const key = `evidence_${name.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]/g, "_")}`;
  sources.push([join(repo, "evidence", name), join(evidence, name), key]);
}

for (const [source, target] of sources) await copyFile(source, target);

const exports = sources.map(([, , key], index) => {
  const target = sources[index][1].replace(/\\/g, "/");
  return `export { default as ${key} } from "${target.startsWith(data ? data.replace(/\\/g, "/") : "") ? `./${target.slice(data.length + 1)}` : target}";`;
});
const body =
  `// Generated by scripts/copy-data.mjs from contracts/deployments.json, contracts/seed.json\n` +
  `// and evidence/*.json. Do not edit by hand; rerun npm run sync:data.\n\n` +
  `${exports.join("\n")}\n`;
await writeFile(join(data, "index.ts"), body, "utf8");

await writeFile(
  join(data, "manifest.json"),
  `${JSON.stringify(
    {
      generatedBy: "scripts/copy-data.mjs",
      sources: sources.map(([source]) => source.replace(`${repo}/`, "")),
    },
    null,
    2,
  )}\n`,
  "utf8",
);

console.log(`copied ${sources.length} data files into src/data`);
